"""
Visualize Label Pipeline: Raw Label → RSLearn Label

Compares 2 versions of labels for N random samples:
1. Raw label TIF (generated by our script)
2. RSLearn processed label (from window layers)

Helps QA that label values are preserved through the pipeline.
"""

import json
import random
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import rasterio

# === CONFIG ===
RAW_LABELS_DIR = Path("dataset_soiling/data/labels")
WINDOWS_DIR = Path("dataset_soiling/windows/default")  # training windows
METADATA_FILE = Path("dataset_soiling/data/metadata/train_metadata.json")

N_SAMPLES = 10
SEED = 42
OUTPUT_DIR = Path("pipeline_visualizations")

random.seed(SEED)


def find_matching_files(windows_dir: Path, raw_labels_dir: Path) -> list:
    """
    Find chips that have both: raw label and rslearn label.
    Returns list of dicts with paths.
    """
    matches = []
    
    for chip_dir in windows_dir.iterdir():
        if not chip_dir.is_dir():
            continue
        
        chip_name = chip_dir.name
        
        # RSLearn label path
        rslearn_label = chip_dir / "layers/label/B1/geotiff.tif"
        
        # Raw label
        raw_label = raw_labels_dir / f"{chip_name}_label.tif"
        
        # Check if rslearn label exists
        if rslearn_label.exists():
            matches.append({
                "chip_name": chip_name,
                "chip_dir": chip_dir,
                "raw_label": raw_label if raw_label.exists() else None,
                "rslearn_label": rslearn_label,
            })
    
    return matches


def load_tif(filepath: Path) -> np.ndarray:
    """Load a single-band TIF."""
    with rasterio.open(filepath) as src:
        return src.read(1)


def load_s2_rgb(chip_dir: Path) -> np.ndarray | None:
    """Load Sentinel-2 RGB from chip."""
    s2_path = chip_dir / "layers/sentinel2_l2a/B01_B02_B03_B04_B05_B06_B07_B08_B8A_B09_B11_B12/geotiff.tif"
    
    if not s2_path.exists():
        return None
    
    with rasterio.open(s2_path) as src:
        bands = []
        for i in [4, 3, 2]:  # B04, B03, B02 for RGB
            band = src.read(i).astype(float)
            p2, p98 = np.percentile(band, [2, 98])
            band = np.clip((band - p2) / (p98 - p2 + 1e-6), 0, 1)
            bands.append(band)
        return np.dstack(bands)


def get_mean_value(arr: np.ndarray, nodata: float = -1) -> float:
    """Get mean value excluding nodata."""
    valid = arr[arr != nodata]
    return np.mean(valid) if len(valid) > 0 else np.nan


def visualize_sample(match: dict, idx: int, output_dir: Path):
    """Create visualization for a single sample."""
    chip_name = match["chip_name"]
    
    # Load data
    rslearn_label = load_tif(match["rslearn_label"])
    
    raw_label = None
    if match["raw_label"] and match["raw_label"].exists():
        raw_label = load_tif(match["raw_label"])
    
    s2_rgb = load_s2_rgb(match["chip_dir"])
    
    # Compute mean values
    raw_val = get_mean_value(raw_label) if raw_label is not None else np.nan
    rslearn_val = get_mean_value(rslearn_label)
    
    # Create figure - 3 columns: S2 RGB, Raw Label, RSLearn Label
    fig, axes = plt.subplots(1, 3, figsize=(14, 4))
    
    # S2 RGB
    if s2_rgb is not None:
        axes[0].imshow(s2_rgb)
        axes[0].set_title("Sentinel-2 RGB", fontsize=11)
    else:
        axes[0].text(0.5, 0.5, "No S2 RGB", ha="center", va="center", fontsize=12)
        axes[0].set_title("Sentinel-2 RGB", fontsize=11)
    axes[0].axis("off")
    
    # Raw label (our generated TIF)
    if raw_label is not None:
        im1 = axes[1].imshow(raw_label, cmap="RdYlGn", vmin=0, vmax=1)
        axes[1].set_title(f"Raw Label (Ours)\nmean: {raw_val:.4f}", fontsize=11)
        plt.colorbar(im1, ax=axes[1], fraction=0.046, pad=0.04)
    else:
        axes[1].text(0.5, 0.5, "Not Found", ha="center", va="center", fontsize=12)
        axes[1].set_title("Raw Label (Ours)\nNOT FOUND", fontsize=11)
    axes[1].axis("off")
    
    # RSLearn label
    im2 = axes[2].imshow(rslearn_label, cmap="RdYlGn", vmin=0, vmax=1)
    axes[2].set_title(f"RSLearn Label\nmean: {rslearn_val:.4f}", fontsize=11)
    axes[2].axis("off")
    plt.colorbar(im2, ax=axes[2], fraction=0.046, pad=0.04)
    
    # Title with comparison stats
    if raw_label is not None:
        label_diff = rslearn_val - raw_val
        suptitle = f"{chip_name}\nRaw→RSLearn diff: {label_diff:+.6f}"
    else:
        suptitle = f"{chip_name}"
    
    plt.suptitle(suptitle, fontsize=12, fontweight="bold")
    plt.tight_layout()
    
    out_path = output_dir / f"label_qa_{idx:02d}_{chip_name}.png"
    plt.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close()
    
    return {
        "chip_name": chip_name,
        "raw_val": raw_val,
        "rslearn_val": rslearn_val,
    }


def print_summary(results: list):
    """Print summary statistics."""
    print("\n" + "=" * 70)
    print("LABEL QA SUMMARY")
    print("=" * 70)
    
    # Filter valid results
    valid = [r for r in results if not np.isnan(r["rslearn_val"])]
    with_raw = [r for r in valid if not np.isnan(r["raw_val"])]
    
    print(f"\n  Samples visualized:              {len(results)}")
    print(f"  With raw labels found:           {len(with_raw)}")
    
    if with_raw:
        raw_to_rslearn_diffs = [r["rslearn_val"] - r["raw_val"] for r in with_raw]
        print(f"\n  RAW → RSLEARN LABEL DIFF:")
        print(f"    Mean diff:                     {np.mean(raw_to_rslearn_diffs):+.6f}")
        print(f"    Max abs diff:                  {np.max(np.abs(raw_to_rslearn_diffs)):.6f}")
        print(f"    Std diff:                      {np.std(raw_to_rslearn_diffs):.6f}")
        
        # Check if values match
        if np.max(np.abs(raw_to_rslearn_diffs)) < 1e-5:
            print(f"\n  ✓ PASS: Labels match perfectly!")
        else:
            print(f"\n  ✗ FAIL: Label mismatch detected!")
    
    print("\n  PER-SAMPLE DETAILS:")
    print("  " + "-" * 56)
    print(f"  {'Chip':<30} {'Raw':>10} {'RSLearn':>10} {'Diff':>10}")
    print("  " + "-" * 56)
    for r in results:
        raw_str = f"{r['raw_val']:.4f}" if not np.isnan(r["raw_val"]) else "N/A"
        diff = r["rslearn_val"] - r["raw_val"] if not np.isnan(r["raw_val"]) else float('nan')
        diff_str = f"{diff:+.6f}" if not np.isnan(diff) else "N/A"
        print(f"  {r['chip_name']:<30} {raw_str:>10} {r['rslearn_val']:>10.4f} {diff_str:>10}")
    
    print("=" * 70)


def main():
    print("Label QA: Raw vs RSLearn")
    print("=" * 70)
    
    # Create output dir
    OUTPUT_DIR.mkdir(exist_ok=True)
    
    # Find matching files
    print(f"\nScanning windows directory: {WINDOWS_DIR}")
    matches = find_matching_files(WINDOWS_DIR, RAW_LABELS_DIR)
    print(f"Found {len(matches)} chips with RSLearn labels")
    
    raw_found = sum(1 for m in matches if m["raw_label"] and m["raw_label"].exists())
    print(f"Of those, {raw_found} have matching raw labels")
    
    if not matches:
        print("ERROR: No matching chips found!")
        return
    
    # Sample
    n_samples = min(N_SAMPLES, len(matches))
    selected = random.sample(matches, n_samples)
    
    print(f"\nSelected {n_samples} samples for visualization")
    print("-" * 70)
    
    # Visualize each
    results = []
    for idx, match in enumerate(selected, 1):
        print(f"[{idx:02d}] Processing {match['chip_name']}...")
        result = visualize_sample(match, idx, OUTPUT_DIR)
        results.append(result)
    
    # Summary
    print_summary(results)
    
    print(f"\nVisualizations saved to: {OUTPUT_DIR}/")
    print("Done!")


if __name__ == "__main__":
    main()